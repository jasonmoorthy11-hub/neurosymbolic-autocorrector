"""Golden dataset for evaluating the autocorrection pipeline.

Each test case represents an agent output that should be classified, validated,
and potentially corrected. The expected outcome defines what the pipeline
SHOULD do — allowing us to measure precision, recall, and F0.5.

Categories:
    - true_positive: Agent output has a real violation that should be corrected
    - true_negative: Agent output is compliant and should be allowed through
    - pii_leak: Agent output contains PII that should be redacted
    - factual_error: Agent output contains incorrect facts
    - escalation: Agent output has a critical violation requiring supervisor
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class ExpectedAction(StrEnum):
    ALLOW = "allow"
    CORRECT = "correct"
    ESCALATE = "escalate"


class EvalCase(BaseModel):
    """A single evaluation test case."""

    id: str
    category: str
    description: str
    agent_text: str
    customer_context: dict[str, Any]
    expected_action: ExpectedAction
    expected_rule_ids: list[str] = Field(default_factory=list)
    expected_pii: bool = False
    expected_facts_wrong: bool = False
    tags: list[str] = Field(default_factory=list)


class GoldenDataset(BaseModel):
    """Collection of test cases for evaluation."""

    name: str
    version: str
    cases: list[EvalCase]

    @property
    def by_category(self) -> dict[str, list[EvalCase]]:
        result: dict[str, list[EvalCase]] = {}
        for case in self.cases:
            result.setdefault(case.category, []).append(case)
        return result

    @property
    def summary(self) -> dict[str, int]:
        counts = {"total": len(self.cases)}
        for cat, cases in self.by_category.items():
            counts[cat] = len(cases)
        return counts


